-- 2) Table CHERCHEUR
CREATE TABLE CHERCHEUR (
  ID_CHERCHEUR    NUMBER        NOT NULL,
  NOM             VARCHAR2(100) NOT NULL,
  PRENOM          VARCHAR2(100),
  EMAIL           VARCHAR2(200),
  GRADE           VARCHAR2(50),
  CIN             VARCHAR2(30),
  PHOTO_PROFIL    VARCHAR2(200) DEFAULT ':/avatar.png',
  CONSTRAINT PK_CHERCHEUR PRIMARY KEY (ID_CHERCHEUR),
  CONSTRAINT UNQ_CHERCHEUR_EMAIL UNIQUE (EMAIL),
  CONSTRAINT UNQ_CHERCHEUR_CIN   UNIQUE (CIN)
);

CREATE SEQUENCE SEQ_CHERCHEUR START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
-- trigger pour remplir automatiquement ID_CHERCHEUR
CREATE OR REPLACE TRIGGER BI_CHERCHEUR
  BEFORE INSERT ON CHERCHEUR
  FOR EACH ROW
BEGIN
  IF :NEW.ID_CHERCHEUR IS NULL THEN
     SELECT SEQ_CHERCHEUR.NEXTVAL INTO :NEW.ID_CHERCHEUR FROM DUAL;
  END IF;
END;
/

-- 3) Table PUBLICATION
CREATE TABLE PUBLICATION (
  ID_PUBLICATION    NUMBER        NOT NULL,
  DOI               VARCHAR2(250) NOT NULL,
  TITRE             VARCHAR2(400) NOT NULL,
  AUTEUR            VARCHAR2(400),
  DATE_PUBLICATION  DATE,
  STATUT            VARCHAR2(30),
  REVUE             VARCHAR2(200),
  ID_CHERCHEUR      NUMBER,
