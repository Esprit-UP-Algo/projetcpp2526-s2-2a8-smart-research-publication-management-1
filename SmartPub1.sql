  CONSTRAINT UNQ_PUBLICATION_DOI UNIQUE (DOI),
  CONSTRAINT FK_PUBLICATION_CHERCHEUR FOREIGN KEY (ID_CHERCHEUR)
    REFERENCES CHERCHEUR (ID_CHERCHEUR) ON DELETE SET NULL,
  CONSTRAINT CK_PUBLICATION_STATUT CHECK (STATUT IN ('soumis','en_revision','accepte','publie','rejete'))
